namespace CADR.Portal.Components.Models.Enums;

/// <summary>
/// Задает константы, определяющие отображаемые иконки сообщения
/// </summary>
public enum MessageBoxIcon
{
    /// <summary>
    /// Окно сообщения содержит символ, состоящий из строчной буквы i в кружке
    /// </summary>
    Information,

    /// <summary>
    /// Окно сообщения содержит символ, состоящий из восклицательного знака в треугольнике
    /// </summary>
    Warning,

    /// <summary>
    /// Окно сообщения содержит символ, состоящий из белого X в кружке
    /// </summary>
    Error,

    /// <summary>
    /// Окно сообщения содержит символ, состоящий из вопросительного знака в кружке
    /// </summary>
    Question
}
